"""Build display assets: header icon (C header), Next Mile splash JPEG and the intro clip."""
import os, struct, subprocess, sys, glob, io
from PIL import Image, ImageOps

HERE = os.path.dirname(os.path.abspath(__file__))
FW = os.path.join(HERE, '..', 'firmware')
ASSETS = os.path.join(HERE, '..', 'assets')
DATA = os.path.join(FW, 'data')
os.makedirs(DATA, exist_ok=True)

def logo_alpha(path):
    """Black-on-white (or transparent) logo -> 8-bit coverage mask, cropped."""
    im = Image.open(path).convert('RGBA')
    bg = Image.new('RGBA', im.size, (255, 255, 255, 255))
    bg.alpha_composite(im)
    mask = ImageOps.invert(bg.convert('L'))
    return mask.crop(mask.getbbox())

def icon_header():
    m = logo_alpha(os.path.join(ASSETS, 'nextmile_logo.png'))
    # mountain only: drop the "NEXT MILE APPAREL" wordmark under it
    w, h = m.size
    rows = [sum(m.crop((0, y, w, y + 1)).getdata()) for y in range(h)]
    gap = next(y for y in range(int(h * 0.5), h) if rows[y] == 0)
    mtn = m.crop((0, 0, w, gap))
    mtn = mtn.crop(mtn.getbbox())
    ih = 26
    iw = round(mtn.size[0] * ih / mtn.size[1])
    mtn = mtn.resize((iw, ih), Image.LANCZOS)
    px = list(mtn.getdata())
    out = ['// Generated by tools/make_assets.py', '#pragma once', '#include <stdint.h>',
           f'static const uint16_t ICON_W = {iw}, ICON_H = {ih};',
           f'static const uint8_t icon_mtn_a8[{iw*ih}] = {{']
    for i in range(0, len(px), 32):
        out.append('  ' + ','.join(str(p) for p in px[i:i + 32]) + ',')
    out.append('};')
    open(os.path.join(FW, 'src', 'icon_gen.h'), 'w').write('\n'.join(out) + '\n')
    print('icon', iw, ih)

def splash():
    m = logo_alpha(os.path.join(ASSETS, 'nextmile_logo.png'))
    W, H = 320, 240
    s = min((W - 100) / m.size[0], (H - 100) / m.size[1])
    m = m.resize((round(m.size[0] * s), round(m.size[1] * s)), Image.LANCZOS)
    img = Image.new('RGB', (W, H), (0, 0, 0))
    white = Image.new('RGB', m.size, (255, 255, 255))
    img.paste(white, ((W - m.size[0]) // 2, (H - m.size[1]) // 2), m)
    img.save(os.path.join(DATA, 'nextmile.jpg'), quality=92, subsampling=0)
    img.save(os.path.join(ASSETS, 'preview_splash_nextmile.png'))
    print('splash ok')

def intro(fps=20, q=6, trim_end=1.0):
    """Video -> intro.bin: u32 frame count, u32 fps, u32 sizes[count], then baseline JPEG frames."""
    src = os.path.join(ASSETS, 'INTRO.mp4')
    dur = float(subprocess.check_output(['ffprobe', '-v', 'error', '-show_entries', 'format=duration',
                                         '-of', 'default=nw=1:nk=1', src]).decode())
    tmp = os.path.join(HERE, '_frames')
    os.makedirs(tmp, exist_ok=True)
    for f in glob.glob(os.path.join(tmp, '*.jpg')):
        os.remove(f)
    subprocess.check_call(['ffmpeg', '-v', 'error', '-y', '-i', src, '-t', f'{dur - trim_end:.2f}', '-an',
                           '-vf', f'fps={fps},scale=320:180:flags=lanczos',
                           '-q:v', str(q), '-pix_fmt', 'yuvj420p', os.path.join(tmp, 'f%04d.jpg')])
    frames = sorted(glob.glob(os.path.join(tmp, '*.jpg')))
    blobs = [open(f, 'rb').read() for f in frames]
    with open(os.path.join(DATA, 'intro.bin'), 'wb') as fh:
        fh.write(struct.pack('<II', len(blobs), fps))
        fh.write(struct.pack(f'<{len(blobs)}I', *[len(b) for b in blobs]))
        for b in blobs:
            fh.write(b)
    print('intro', len(blobs), 'frames', sum(map(len, blobs)), 'bytes, max frame', max(map(len, blobs)))

if __name__ == '__main__':
    icon_header()
    splash()
    intro()
