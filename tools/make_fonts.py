"""Render TTF fonts to LovyanGFX/TFT_eSPI .vlw smooth fonts and emit a C header."""
import struct, freetype, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'firmware', 'src', 'fonts_gen.h')
ASCII = ''.join(chr(c) for c in range(32, 127))

FONTS = [
    # name, ttf, {axis: value}, pixel size, chars
    ('font_big',   'Oswald.ttf', {'wght': 600}, 76, ' 0123456789,.-'),
    ('font_title', 'Oswald.ttf', {'wght': 600}, 26, ASCII),
    ('font_mid',   'Oswald.ttf', {'wght': 500}, 20, ASCII),
    ('font_label', 'Oswald.ttf', {'wght': 500}, 15, ASCII + '\u00b0'),
    ('font_body',  'Inter.ttf',  {'wght': 500, 'opsz': 14}, 14, ASCII),
]

def set_axes(face, axes):
    info = face.get_variation_info()
    coords = []
    for ax in info.axes:
        tag = ax.tag
        coords.append(axes.get(tag, ax.default))
    face.set_var_design_coords(coords)

def vlw(ttf, axes, px, chars):
    face = freetype.Face(os.path.join(HERE, ttf))
    set_axes(face, axes)
    face.set_pixel_sizes(0, px)
    ascent = face.size.ascender >> 6
    descent = -(face.size.descender >> 6)
    glyphs, bitmaps = [], []
    chars = ''.join(sorted(set(chars)))  # LovyanGFX binary-searches glyphs by codepoint
    for ch in chars:
        face.load_char(ch, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_NORMAL)
        g = face.glyph
        bm = g.bitmap
        w, h = bm.width, bm.rows
        data = bytearray()
        for r in range(h):
            data += bytes(bm.buffer[r * bm.pitch: r * bm.pitch + w])
        adv = (g.advance.x + 32) >> 6
        glyphs.append(struct.pack('>7i', ord(ch), h, w, adv, g.bitmap_top, g.bitmap_left, 0))
        bitmaps.append(bytes(data))
    head = struct.pack('>6i', len(chars), 11, px, 0, ascent, descent)
    return head + b''.join(glyphs) + b''.join(bitmaps)

def main():
    out = ['// Generated by tools/make_fonts.py. Do not edit.', '#pragma once', '#include <stdint.h>', '']
    total = 0
    for name, ttf, axes, px, chars in FONTS:
        blob = vlw(ttf, axes, px, chars)
        total += len(blob)
        out.append(f'static const uint8_t {name}_vlw[{len(blob)}] = {{')
        for i in range(0, len(blob), 24):
            out.append('  ' + ','.join(str(b) for b in blob[i:i + 24]) + ',')
        out.append('};\n')
    open(OUT, 'w').write('\n'.join(out))
    print('wrote', OUT, total, 'bytes')

if __name__ == '__main__':
    main()
