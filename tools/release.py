"""Signed OTA releases.

  python3 tools/release.py keygen      # once: makes the signing key (keep it private!) + firmware/src/ota_pubkey.h
  python3 tools/release.py publish N   # build both envs as version N, sign, write docs/fw/ (push to publish)

The private key lives outside the repo (NEXTMILE_OTA_KEY, default ~/.nextmile/ota_signing_key.pem).
Every tracker only installs firmware signed by it, so back it up: lose it and boards can't be updated.
"""
import base64, hashlib, json, os, re, subprocess, sys
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, utils

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
FW = os.path.join(ROOT, 'firmware')
OUT = os.path.join(ROOT, 'docs', 'fw')
PUB_H = os.path.join(FW, 'src', 'ota_pubkey.h')
KEY = os.path.expanduser(os.environ.get('NEXTMILE_OTA_KEY', '~/.nextmile/ota_signing_key.pem'))
BASE = 'https://ds3design.github.io/nextmile-tracker/fw/'
ENVS = ['cyd_ili9341', 'cyd_st7789']
PIO = os.path.expanduser('~/.local/bin/pio') if os.path.exists(os.path.expanduser('~/.local/bin/pio')) else 'pio'


def write_pub(key):
    pem = key.public_key().public_bytes(serialization.Encoding.PEM,
                                        serialization.PublicFormat.SubjectPublicKeyInfo).decode()
    open(PUB_H, 'w').write('// Generated by tools/release.py keygen. Public half of the DS3design OTA signing key.\n'
                           '#pragma once\nstatic const char OTA_PUBKEY_PEM[] = R"PEM(\n' + pem + ')PEM";\n')


def keygen():
    if os.path.exists(KEY):
        sys.exit(f'{KEY} already exists; refusing to overwrite')
    os.makedirs(os.path.dirname(KEY), exist_ok=True)
    key = ec.generate_private_key(ec.SECP256R1())
    fd = os.open(KEY, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    os.write(fd, key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                                   serialization.NoEncryption()))
    os.close(fd)
    write_pub(key)
    print('signing key ->', KEY, '(back this up somewhere safe)')
    print('public key  ->', PUB_H)


def publish(version):
    key = serialization.load_pem_private_key(open(KEY, 'rb').read(), None)
    ini = os.path.join(FW, 'platformio.ini')
    s = open(ini).read()
    open(ini, 'w').write(re.sub(r'-DFW_VERSION=\d+', f'-DFW_VERSION={version}', s))
    os.makedirs(OUT, exist_ok=True)
    builds = {}
    for env in ENVS:
        subprocess.check_call([PIO, 'run', '-e', env], cwd=FW)
        data = open(os.path.join(FW, '.pio', 'build', env, 'firmware.bin'), 'rb').read()
        digest = hashlib.sha256(data).digest()
        sig = key.sign(digest, ec.ECDSA(utils.Prehashed(hashes.SHA256())))
        name = f'{env}-v{version}.bin'
        open(os.path.join(OUT, name), 'wb').write(data)
        builds[env] = {'url': BASE + name, 'size': len(data), 'sha256': digest.hex(),
                       'sig': base64.b64encode(sig).decode()}
    json.dump({'version': version, 'builds': builds}, open(os.path.join(OUT, 'manifest.json'), 'w'), indent=1)
    print('wrote', OUT, 'version', version)


if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else ''
    if cmd == 'keygen':
        keygen()
    elif cmd == 'publish' and len(sys.argv) == 3:
        publish(int(sys.argv[2]))
    else:
        print(__doc__)
