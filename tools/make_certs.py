"""Pick a few long-lived root CAs from certifi so HTTPS to Strava survives a CA change."""
import certifi, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'firmware', 'src', 'certs_gen.h')
WANT = ['Go Daddy Root Certificate Authority - G2', 'Starfield Root Certificate Authority - G2',
        'ISRG Root X1', 'ISRG Root X2', 'Amazon Root CA 1', 'DigiCert Global Root G2',
'GTS Root R1', 'USERTrust RSA Certification Authority']
pem = open(certifi.where()).read()
blocks = re.findall(r'# Label: "([^"]+)".*?(-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----)', pem, re.S)
got = [(l, c) for l, c in blocks if l in WANT]
missing = set(WANT) - {l for l, _ in got}
assert not missing, missing
body = '\n'.join(c for _, c in got) + '\n'
open(OUT, 'w').write('// Generated by tools/make_certs.py. Do not edit.\n#pragma once\n'
                     'static const char ROOT_CAS[] = R"PEM(\n' + body + ')PEM";\n')
print('wrote', len(got), 'roots', len(body), 'bytes')
